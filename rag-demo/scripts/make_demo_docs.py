"""Генерирует демо-документы вымышленной компании для показа и приёмки."""
from pathlib import Path

import docx

OUT = Path(__file__).resolve().parent.parent / "demo_docs"
NOTE = "Документ вымышленной компании ООО «Ромашка-Сервис», создан для демонстрации."

DOCS = {
    "Регламент_персонала.docx": [
        "Правила внутреннего распорядка ООО «Ромашка-Сервис»",
        "Рабочий день длится с 9:00 до 18:00, перерыв на обед — один час.",
        "Ежегодный оплачиваемый отпуск составляет 28 календарных дней.",
        "Заявление на отпуск подаётся руководителю не позднее чем за 14 дней до его начала.",
        "Удалённая работа допускается не более 2 дней в неделю по согласованию с руководителем.",
    ],
    "Прайс_услуг.docx": [
        "Прайс-лист ООО «Ромашка-Сервис» на ИТ-обслуживание",
        "Тариф «Базовый»: 12 000 рублей в месяц, до 10 рабочих мест.",
        "Тариф «Расширенный»: 25 000 рублей в месяц, до 30 рабочих мест, приоритетная поддержка.",
        "Выезд специалиста в офис клиента: 3 500 рублей за визит.",
        "При оплате за год вперёд предоставляется скидка 10%.",
    ],
    "Договор_оказания_услуг.docx": [
        "Договор оказания услуг (типовая форма) ООО «Ромашка-Сервис»",
        "Заказчик оплачивает счёт в течение 5 рабочих дней с даты его получения.",
        "За просрочку оплаты начисляется пеня 0,1% от суммы долга за каждый день просрочки.",
        "Любая из сторон может расторгнуть договор, письменно уведомив другую сторону за 30 календарных дней.",
        "Гарантия на выполненные работы составляет 6 месяцев.",
    ],
}


def main() -> None:
    OUT.mkdir(exist_ok=True)
    for name, paragraphs in DOCS.items():
        document = docx.Document()
        document.add_paragraph(NOTE)
        for p in paragraphs:
            document.add_paragraph(p)
        document.save(OUT / name)
        print("written", OUT / name)


if __name__ == "__main__":
    main()
